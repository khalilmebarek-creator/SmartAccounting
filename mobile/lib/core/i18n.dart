  static const List<String> supportedLanguages = ['ar', 'en', 'fr'];

  static Map<String, String> _table(String lang) {
    switch (lang) {
      case 'en':
        return en;
      case 'fr':
        return fr;
      default:
        return ar;
    }
  }

  /// Translate a key for a language, falling back to Arabic.
  static String t(String lang, String key) =>
      _table(lang)[key] ?? ar[key] ?? key;

  /// Substitute `{n}` placeholders with [values] (positional).
  static String format(String text, List<String> values) {
    if (values.isEmpty) return text;
    var out = text;
    for (var i = 0; i < values.length; i++) {
      out = out.replaceAll('{$i}', values[i]);
    }
    out = out.replaceAll(RegExp(r'\{n\}'), values[0]);
    return out;
  }
